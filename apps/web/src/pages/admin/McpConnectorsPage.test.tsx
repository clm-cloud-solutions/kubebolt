// user-event fires its events through its own copy of @testing-library/dom
// (10.x), which React Testing Library 14 — built on 9.x — never hooks up to
// act(): every update an event causes lands outside act, and React warns once
// per keystroke. Going through act settles each interaction before the next
// assertion looks, and keeps a real warning from drowning in that noise.
const user = {
  click: (el: Element) => act(() => userEvent.click(el)),
  type: (el: Element, text: string) => act(() => userEvent.type(el, text)),
  clear: (el: Element) => act(() => userEvent.clear(el)),
  selectOptions: (el: Element, value: string) => act(() => userEvent.selectOptions(el, value)),
}

