function LocationProbe() {
  const loc = useLocation()
  return <div data-testid="location">{loc.search}</div>
}

function renderPage(search = '?tab=connectors', opts: { launcher?: boolean; qc?: QueryClient } = {}) {
  const qc = opts.qc ?? new QueryClient({ defaultOptions: { queries: { retry: false } } })
  return render(
    <QueryClientProvider client={qc}>
      <MemoryRouter initialEntries={[`/admin/ai${search}`]}>
        <Routes>
          <Route
            path="/admin/ai"
            element={
              <>
                <McpConnectorsPage />
                <LocationProbe />
                {opts.launcher && <CopilotToggle />}
              </>
            }
          />
        </Routes>
      </MemoryRouter>
    </QueryClientProvider>,
  )
}

