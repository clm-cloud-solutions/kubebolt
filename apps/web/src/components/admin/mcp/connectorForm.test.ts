// The external ID KubeBolt generated for the org: the admin view creates it
// before anything is saved, so every AWS payload carries it.
const EXTERNAL_ID = 'a1b2c3d4e5f6'

// An AWS connector as the admin API describes it (CONTRACT §5): two auth
// modes, the external ID generated by KubeBolt and nothing secret.
function aws(over: Partial<McpConnector> = {}): McpConnector {
  return {
    id: 'aws',
    name: 'Amazon Web Services',
    category: 'cloud',
    description: '',
    tags: [],
    docsURL: '',
    minPlan: 'team',
    entitled: true,
    status: 'available',
    enabled: false,
    paused: false,
    kobiMinRole: 'editor',
    mode: '',
    authModes: [
      {
        id: 'assume-role',
        label: 'IAM role',
        description: '',
        selfHostedOnly: false,
        fields: [
          { name: 'roleArn', label: 'Role ARN', secret: false, required: true },
          { name: 'externalId', label: 'External ID', secret: false, required: true, generated: true },
          { name: 'region', label: 'Region', secret: false, required: true },
          { name: 'hostRegion', label: 'MCP endpoint region', secret: false, required: false, advanced: true, default: 'us-east-1' },
        ],
      },
      {
        id: 'ambient',
        label: "This machine's credentials",
        description: '',
        selfHostedOnly: true,
        fields: [
          { name: 'region', label: 'Region', secret: false, required: true },
          { name: 'profile', label: 'Profile', secret: false, required: false },
        ],
      },
    ],
    families: [],
    never: [],
    tools: { kobi: [], autopilot: [] },
    config: { fields: { externalId: EXTERNAL_ID }, secretsConfigured: {}, secretsUnreadable: [] },
    setupGuide: { steps: [] },
    ...over,
  }
}

const saved = () =>
  aws({
    status: 'enabled',
    enabled: true,
    mode: 'assume-role',
    config: {
      fields: { roleArn: 'arn:aws:iam::123456789012:role/kb', externalId: EXTERNAL_ID, region: 'eu-west-1', hostRegion: 'eu-central-1' },
      secretsConfigured: {},
      secretsUnreadable: [],
    },
  })

// A GCP connector: its service-account key is the secret a connector stores.
function gcp(over: Partial<McpConnector> = {}): McpConnector {
  return {
    ...aws(),
    id: 'gcp',
    name: 'Google Cloud',
    authModes: [
      {
        id: 'service-account',
        label: 'Service account key',
        description: '',
        selfHostedOnly: false,
        fields: [
          { name: 'projectId', label: 'Project ID', secret: false, required: true },
          { name: 'credentialJSON', label: 'Credential JSON', secret: true, required: true, multiline: true },
          { name: 'location', label: 'Default location', secret: false, required: false, advanced: true },
        ],
      },
      {
        id: 'adc',
        label: 'Application Default Credentials',
        description: '',
        selfHostedOnly: true,
        fields: [
          { name: 'projectId', label: 'Project ID', secret: false, required: true },
          { name: 'location', label: 'Default location', secret: false, required: false, advanced: true },
        ],
      },
    ],
    config: { fields: {}, secretsConfigured: {}, secretsUnreadable: [] },
    ...over,
  }
}

const savedGCP = () =>
  gcp({
    status: 'enabled',
    enabled: true,
    mode: 'service-account',
    config: { fields: { projectId: 'shop-prod' }, secretsConfigured: { credentialJSON: true }, secretsUnreadable: [] },
  })

describe('initialForm', () => {
  it('starts a new connector on its first mode, with defaults filled', () => {
    const f = initialForm(aws())
    expect(f.mode).toBe('assume-role')
    expect(f.fields).toEqual({ roleArn: '', externalId: EXTERNAL_ID, region: '', hostRegion: 'us-east-1', profile: '' })
    expect(f.secrets).toEqual({})
  })

  it('shows what is stored, and never a secret', () => {
    const f = initialForm(saved())
    expect(f.fields.region).toBe('eu-west-1')
    expect(f.fields.hostRegion).toBe('eu-central-1')
    const g = initialForm(savedGCP())
    expect(g.fields).not.toHaveProperty('credentialJSON')
    expect(g.secrets).toEqual({})
  })

  it('prefills a detected region only on a connector that was never saved', () => {
    const guess = { field: 'region', value: 'us-west-2', source: 'prod-eks' }
    expect(initialForm(aws(), guess).fields.region).toBe('us-west-2')
    const noRegion = saved()
    noRegion.config.fields = { roleArn: 'arn:aws:iam::1:role/x', region: '' }
    expect(initialForm(noRegion, guess).fields.region).toBe('')
  })

  it('tolerates the nil slices a Go backend serialises as null', () => {
    const c = aws({ authModes: null })
    c.config = { fields: null, secretsConfigured: null, secretsUnreadable: null }
    expect(initialForm(c)).toEqual({ mode: '', fields: {}, secrets: {}, kobiMinRole: 'editor' })
  })
})

describe('secrets: blank means keep', () => {
  it('leaves a blank secret out of the save — never ""', () => {
    const c = savedGCP()
    const form = initialForm(c)
    form.fields.location = 'us-central1'
    const body = buildPut(c, form, { enable: false })
    expect(body.secrets).toBeUndefined()
    expect(JSON.stringify(body)).not.toContain('"credentialJSON"')
  })

  it('sends a typed secret, trimmed', () => {
    const c = savedGCP()
    const form = initialForm(c)
    form.secrets.credentialJSON = '  {"type": "service_account"}  '
    expect(buildPut(c, form, { enable: false }).secrets).toEqual({ credentialJSON: '{"type": "service_account"}' })
  })

  it('treats a whitespace-only secret as blank', () => {
    const c = savedGCP()
    const form = initialForm(c)
    form.secrets.credentialJSON = '   '
    expect(dirtyFields(c, initialForm(c), form).size).toBe(0)
    expect(buildPut(c, form, { enable: false }).secrets).toBeUndefined()
  })
})

describe('buildPut', () => {
  it('turns the connector on only on the first save', () => {
    const c = aws()
    const form = initialForm(c)
    form.fields.roleArn = 'arn:aws:iam::123456789012:role/kb'
    form.fields.region = 'us-east-1'
    expect(buildPut(c, form, { enable: true })).toEqual({
      enabled: true,
      mode: 'assume-role',
      fields: { roleArn: 'arn:aws:iam::123456789012:role/kb', region: 'us-east-1', hostRegion: 'us-east-1' },
    })
    expect(buildPut(saved(), initialForm(saved()), { enable: false }).enabled).toBeUndefined()
  })

  it('sends only the fields of the chosen mode', () => {
    const c = saved()
    const form = initialForm(c)
    form.mode = 'ambient'
    form.fields.profile = 'readonly'
    expect(buildPut(c, form, { enable: false })).toEqual({
      mode: 'ambient',
      fields: { region: 'eu-west-1', profile: 'readonly' },
    })
  })
})

describe('dirtyFields and missingRequired', () => {
  it('marks exactly the fields that changed', () => {
    const c = saved()
    const initial = initialForm(c)
    const form = { ...initial, fields: { ...initial.fields, region: 'us-east-2' } }
    expect([...dirtyFields(c, initial, form)]).toEqual(['region'])
  })

  it('counts a stored secret as present, unless it can no longer be read', () => {
    const c = savedGCP()
    expect(missingRequired(c, initialForm(c))).toEqual([])
    c.config.secretsUnreadable = ['credentialJSON']
    expect(missingRequired(c, initialForm(c)).map((f) => f.name)).toEqual(['credentialJSON'])
  })

  it('does not credit a stored secret to a different mode', () => {
    const c = savedGCP()
    const form = initialForm(c)
    form.mode = 'adc'
    // adc has no secret, so nothing is missing…
    expect(missingRequired(c, form)).toEqual([])
    // …but a never-saved connector must have its secret typed.
    expect(missingRequired(gcp(), initialForm(gcp())).map((f) => f.name)).toEqual(['projectId', 'credentialJSON'])
    // The generated external ID is never asked for.
    expect(missingRequired(aws(), initialForm(aws())).map((f) => f.name)).toEqual(['roleArn', 'region'])
  })
})

describe('buildDraft', () => {
  it('tests the stored config when nothing changed — that refreshes "Verified"', () => {
    const c = saved()
    expect(buildDraft(c, false, initialForm(c))).toBeUndefined()
  })

  it('tests the unsaved form otherwise, blank secrets left to the stored value', () => {
    const c = saved()
    const form = initialForm(c)
    form.fields.region = 'us-east-2'
    expect(buildDraft(c, true, form)).toEqual({
      mode: 'assume-role',
      fields: { roleArn: 'arn:aws:iam::123456789012:role/kb', region: 'us-east-2', hostRegion: 'eu-central-1' },
    })
  })

  it('always sends the form for a connector that was never saved', () => {
    const draft = buildDraft(aws(), false, initialForm(aws()))
    expect(draft?.mode).toBe('assume-role')
  })
})

describe('detectRegion', () => {
  const cl = (over: Partial<ClusterInfo>): ClusterInfo => ({
    name: 'c',
    context: 'c',
    server: '',
    active: false,
    status: 'connected',
    ...over,
  })

  it('prefers the active cluster on the same provider', () => {
    const clusters = [
      cl({ name: 'a', cloudProvider: 'AWS', region: 'us-west-2' }),
      cl({ name: 'b', cloudProvider: 'AWS', region: 'eu-west-1', active: true, displayName: 'prod' }),
    ]
    expect(detectRegion('aws', clusters)).toEqual({ field: 'region', value: 'eu-west-1', source: 'prod' })
  })

  it('never borrows a region from another provider', () => {
    expect(detectRegion('aws', [cl({ cloudProvider: 'Google Cloud', region: 'us-central1', active: true })])).toBeNull()
    expect(detectRegion('aws', [cl({ cloudProvider: 'AWS' })])).toBeNull()
    expect(detectRegion('aws', null)).toBeNull()
  })
})

describe('relativeTime', () => {
  const now = Date.parse('2026-09-24T12:00:00Z')
  it('reads coarse and human', () => {
    expect(relativeTime('2026-09-24T11:59:30Z', now)).toBe('just now')
    expect(relativeTime('2026-09-24T11:55:00Z', now)).toBe('5 min ago')
    expect(relativeTime('2026-09-24T09:00:00Z', now)).toBe('3 h ago')
    expect(relativeTime('2026-09-22T12:00:00Z', now)).toBe('2 days ago')
    expect(relativeTime('nope', now)).toBe('')
    expect(relativeTime(undefined, now)).toBe('')
  })
})

// SEC-3: the AWS external ID is KubeBolt's, not the customer's — created once
// per org and only copied. The API refuses a save or a test that carries it,
// so the form must never send it, never count it as a change, and never ask
// for it.
describe('generated fields', () => {
  const withGenerated = () =>
    aws({
      status: 'enabled',
      enabled: true,
      mode: 'assume-role',
      authModes: [
        {
          id: 'assume-role',
          label: 'IAM role',
          description: '',
          selfHostedOnly: false,
          fields: [
            { name: 'roleArn', label: 'Role ARN', secret: false, required: true },
            { name: 'externalId', label: 'External ID', secret: false, required: true, generated: true },
            { name: 'region', label: 'Region', secret: false, required: true },
          ],
        },
      ],
      config: {
        fields: { roleArn: 'arn:aws:iam::123456789012:role/kb', externalId: 'a1b2c3', region: 'us-east-1' },
        secretsConfigured: {},
        secretsUnreadable: [],
      },
    })

  it('shows the value but never sends it, in a save or a test', () => {
    const c = withGenerated()
    const form = initialForm(c)
    expect(form.fields.externalId).toBe('a1b2c3')
    form.fields.region = 'eu-west-1'
    expect(buildPut(c, form, { enable: false }).fields).toEqual({
      roleArn: 'arn:aws:iam::123456789012:role/kb',
      region: 'eu-west-1',
    })
    expect(buildDraft(c, true, form)?.fields).not.toHaveProperty('externalId')
    // A first save of a connector never saved before leaves it out as well.
    const fresh = { ...withGenerated(), mode: '', enabled: false }
    expect(buildPut(fresh, initialForm(fresh), { enable: true }).fields).not.toHaveProperty('externalId')
  })

  it('is neither a change nor something to fill in', () => {
    const c = withGenerated()
    const initial = initialForm(c)
    const form = { ...initial, fields: { ...initial.fields, externalId: 'edited' } }
    expect(dirtyFields(c, initial, form).size).toBe(0)
    const empty = withGenerated()
    empty.config.fields = { roleArn: 'arn:aws:iam::123456789012:role/kb', region: 'us-east-1' }
    expect(missingRequired(empty, initialForm(empty))).toEqual([])
  })
})

// SEC-4: who may use the connector in Kobi. Not configuration — changing it
// alone must not resend the config (which would count as a save of it) nor
// make Test send a draft instead of testing what is stored.
describe('Kobi role floor', () => {
  it('starts from the stored floor, the default when none is set', () => {
    expect(initialForm(saved()).kobiMinRole).toBe('editor')
    // An older payload without the field reads as the default, never as "".
    expect(initialForm(aws({ kobiMinRole: undefined as never })).kobiMinRole).toBe('editor')
    expect(initialForm(aws({ kobiMinRole: 'admin' })).kobiMinRole).toBe('admin')
  })

  it('goes out alone when it is the only change', () => {
    const c = saved()
    const initial = initialForm(c)
    const form = { ...initial, kobiMinRole: 'admin' as const }
    const dirty = dirtyFields(c, initial, form)
    expect([...dirty]).toEqual(['kobiMinRole'])
    expect(configDirty(dirty)).toBe(false)
    expect(buildPut(c, form, { enable: false })).toEqual({ kobiMinRole: 'admin' })
    expect(buildDraft(c, configDirty(dirty), form)).toBeUndefined()
  })

  it('rides along with a config change, and is left out when unchanged', () => {
    const c = saved()
    const form = { ...initialForm(c), kobiMinRole: 'viewer' as const }
    form.fields.region = 'us-east-2'
    expect(buildPut(c, form, { enable: false })).toMatchObject({ kobiMinRole: 'viewer', fields: { region: 'us-east-2' } })
    const unchanged = initialForm(c)
    unchanged.fields.region = 'us-east-2'
    expect(buildPut(c, unchanged, { enable: false })).not.toHaveProperty('kobiMinRole')
  })

  it('is part of the first save when the admin chose it before enabling', () => {
    const c = aws()
    const form = { ...initialForm(c), kobiMinRole: 'admin' as const }
    expect(buildPut(c, form, { enable: true })).toMatchObject({ enabled: true, kobiMinRole: 'admin', mode: 'assume-role' })
  })
})

// UI-7: the Azure sidecar and "this machine's credentials" store nothing
// secret; the drawer must not talk about stored credentials there.
describe('storesSecrets', () => {
  it('follows the stored mode, not the connector', () => {
    expect(storesSecrets(savedGCP())).toBe(true)
    expect(storesSecrets({ ...savedGCP(), mode: 'adc', config: { fields: { projectId: 'shop-prod' }, secretsConfigured: {}, secretsUnreadable: [] } }))
      .toBe(false)
    // The AWS role stores no secret: its external ID is generated, not kept.
    expect(storesSecrets(saved())).toBe(false)
    expect(storesSecrets(aws({ mode: 'ambient', config: { fields: { region: 'us-east-1' }, secretsConfigured: {}, secretsUnreadable: [] } })))
      .toBe(false)
  })
})

// P6: a connector the install offers no way to sign in to (Azure on a
// multi-tenant install) is not waiting on a plan — no upgrade turns it on.
describe('isPlanLocked', () => {
  it('locks a connector the plan leaves out', () => {
    expect(isPlanLocked(aws({ entitled: false, status: 'plan', upgradeTo: 'team' }))).toBe(true)
    expect(isPlanLocked(aws())).toBe(false)
  })

  it('never locks one the install does not offer, whatever the plan says', () => {
    expect(isPlanLocked(aws({ entitled: false, status: 'plan', upgradeTo: 'team', authModes: [] }))).toBe(false)
    expect(isPlanLocked(aws({ entitled: false, status: 'plan', authModes: null }))).toBe(false)
  })
})

// The plan a locked card names, and whether the org can buy it now: the
// card's CTA is Billing for one, a conversation for the other.
describe('lockedPlan', () => {
  const locked = (over: Partial<McpConnector>) => aws({ entitled: false, status: 'plan', ...over })

  it('names the plan on sale that unlocks it, which may sit above the catalog minimum', () => {
    expect(lockedPlan(locked({ minPlan: 'team', upgradeTo: 'team' }))).toEqual({ plan: 'team', buyable: true })
    expect(lockedPlan(locked({ minPlan: 'team', upgradeTo: 'business' }))).toEqual({ plan: 'business', buyable: true })
  })

  it('falls back to the catalog minimum when nothing on sale unlocks it', () => {
    expect(lockedPlan(locked({ minPlan: 'business', upgradeTo: '' }))).toEqual({ plan: 'business', buyable: false })
    expect(lockedPlan(locked({ minPlan: 'business', upgradeTo: undefined }))).toEqual({ plan: 'business', buyable: false })
  })

  it('is null where no upgrade turns it on', () => {
    expect(lockedPlan(aws())).toBeNull()
    expect(lockedPlan(locked({ upgradeTo: 'team', authModes: [] }))).toBeNull()
  })
})

// Wave 6: offered is the install's word, not the stored mode's — a mode saved
// before the install stopped offering it does not make the connector offered.
describe('isOffered', () => {
  it('is whether the install lists any way of signing in', () => {
    expect(isOffered(aws())).toBe(true)
    expect(isOffered(aws({ authModes: [] }))).toBe(false)
    expect(isOffered(aws({ authModes: null }))).toBe(false)
    expect(isOffered(aws({ authModes: [], mode: 'ambient', enabled: true }))).toBe(false)
  })
})

// The Connection section's "point KubeBolt at another …" names what the mode
// really has: AWS has no subscription and Azure no region.
describe('settingsReach', () => {
  const f = (name: string, extra: Partial<McpFieldSchema> = {}): McpFieldSchema => ({ name, label: name, secret: false, required: true, ...extra })
  const mode = (fields: McpFieldSchema[]): McpAuthMode => ({ id: 'm', label: 'm', description: '', selfHostedOnly: true, fields })
  it('names each connector by its own settings', () => {
    expect(settingsReach(mode([f('region'), f('hostRegion', { advanced: true })]))).toBe(' Change the settings to point KubeBolt at another region.')
    expect(settingsReach(mode([f('subscriptionId')]))).toBe(' Change the settings to point KubeBolt at another subscription.')
    expect(settingsReach(mode([f('projectId')]))).toBe(' Change the settings to point KubeBolt at another project.')
    expect(settingsReach(mode([f('roleArn'), f('externalId', { generated: true }), f('region')]))).toBe(
      ' Change the settings to point KubeBolt at another role or region.',
    )
  })
  it('says nothing when the mode has no setting it can name', () => {
    expect(settingsReach(mode([f('credentialJSON', { secret: true })]))).toBe('')
    expect(settingsReach(undefined)).toBe('')
  })
})
