#!/usr/bin/env bash
# Regenerates ksm_names.go: every metric name kube-state-metrics documents, in
# the releases listed below, minus the custom-resource-state examples
# (kube_customresource_*), whose names each customer chooses in their own
# config and so are never core.
#
# docs/design/ is left out: it illustrates naming rules with made-up names
# (kube_pod_total) that no release exports.
#
# Older releases stay in the list on purpose: a customer whose Prometheus runs
# an old kube-state-metrics, or OpenCost's KSM-compatible copies (it still
# publishes the v1 names, kube_node_status_allocatable_cpu_cores…), sends names
# the current docs no longer carry.
#
# Needs the GitHub CLI (gh), authenticated. Run from this directory:
#   ./gen_ksm_names.sh > ksm_names.go && gofmt -w ksm_names.go
set -euo pipefail

TAGS=(v1.9.8 v2.0.0 v2.10.0 v2.20.0)
REPO=kubernetes/kube-state-metrics
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

for tag in "${TAGS[@]}"; do
  gh api "repos/$REPO/git/trees/$tag?recursive=1" \
    --jq '.tree[] | select(.path|startswith("docs/")) | select(.path|startswith("docs/design/")|not) | select(.path|endswith(".md")) | .path' |
    while read -r path; do
      gh api "repos/$REPO/contents/$path?ref=$tag" --jq .content | base64 -d
    done >>"$tmp/docs.md"
done

grep -oE '\bkube_[a-z0-9_]+' "$tmp/docs.md" |
  grep -v '_$' |
  grep -v '^kube_customresource_' |
  sort -u >"$tmp/names.txt"

cat <<EOF
// Code generated by gen_ksm_names.sh; DO NOT EDIT.
//
// Every metric name kube-state-metrics documents in ${TAGS[*]}, minus
// kube_customresource_* (custom-resource-state metrics, named by each
// customer's own config).

package metriccatalog

var ksmNames = []string{
EOF
sed 's/.*/\t"&",/' "$tmp/names.txt"
echo "}"
